
import os
import sqlite3
import psycopg
from psycopg.rows import dict_row

SQLITE_PATH = "food_bridge.db"
DATABASE_URL = os.environ.get("DATABASE_URL")

if not DATABASE_URL:
    raise RuntimeError("DATABASE_URL is not set.")

tables = {
    "users": ["id", "name", "email", "password", "role"],
    "donations": [
        "id", "food_name", "quantity", "location", "contact", "donor_id"
    ],
    "donation_requests": [
        "id", "donation_id", "receiver_id", "status", "created_at"
    ],
}

source = sqlite3.connect(SQLITE_PATH)
source.row_factory = sqlite3.Row

try:
    with psycopg.connect(DATABASE_URL, row_factory=dict_row) as target:
        with target.cursor() as cur:
           cur.execute("""
              CREATE TABLE IF NOT EXISTS users (
              id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
              name TEXT NOT NULL,
              email TEXT UNIQUE NOT NULL,
              password TEXT NOT NULL,
              role TEXT NOT NULL DEFAULT 'receiver'
              )
         """)

           cur.execute("""
               CREATE TABLE IF NOT EXISTS donations (
               id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
               food_name TEXT NOT NULL,
               quantity TEXT NOT NULL,
               location TEXT NOT NULL,
               contact TEXT NOT NULL DEFAULT '',
               donor_id INTEGER REFERENCES users(id)
               )
        """)

           cur.execute("""
               CREATE TABLE IF NOT EXISTS donation_requests (
               id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
               donation_id INTEGER NOT NULL REFERENCES donations(id),
               receiver_id INTEGER NOT NULL REFERENCES users(id),
               status TEXT NOT NULL DEFAULT 'Pending',
               created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
               UNIQUE(donation_id, receiver_id)
              )
    """)

           for table in tables:
              cur.execute(f"SELECT COUNT(*) AS total FROM {table}")
              if cur.fetchone()["total"] != 0:
                      raise RuntimeError(
                          f"PostgreSQL table '{table}' is not empty. "
                          "Migration stopped safely."
                      )

            # Copy data in foreign-key order.
           for table, columns in tables.items():
                column_list = ", ".join(columns)
                placeholders = ", ".join(["%s"] * len(columns))

                rows = source.execute(
                    f"SELECT {column_list} FROM {table}"
                ).fetchall()

                for row in rows:
                    values = tuple(row[column] for column in columns)
                    cur.execute(
                        f"INSERT INTO {table} ({column_list}) "
                        f"VALUES ({placeholders})",
                        values
                    )

                print(f"{table}: copied {len(rows)} rows")

            # Reset identity sequences after preserving IDs.
           for table in tables:
                cur.execute(
                    f"""
                    SELECT setval(
                        pg_get_serial_sequence('{table}', 'id'),
                        COALESCE(MAX(id), 1),
                        MAX(id) IS NOT NULL
                    )
                    FROM {table}
                    """
                )

    print("Migration completed successfully!")

finally:
    source.close()
